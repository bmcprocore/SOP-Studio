#!/usr/bin/env node
/**
 * sync-seed.js — rewrite the app's built-in RFI_SEED from the master library file.
 *
 * There were two copies of the same template: a hand-written one embedded in the app (what the
 * "Seed" button installs) and the master library under templates/. They had drifted — the embedded
 * copy was missing procedureIntro, closeoutIntro and _personas, so every SOP seeded that way
 * printed "[Intro to the steps.]", "[Intro.]" and an empty access panel.
 *
 * This makes the file the single source and the embedded copy a generated artefact.
 * Run it after editing a master library:   node scripts/sync-seed.js
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const APP = path.join(ROOT, 'app', 'SOP_Studio_v0.1.html');

function newestMasterLibrary() {
  const dir = path.join(ROOT, 'templates', 'rfi');
  const files = fs.readdirSync(dir).filter((f) => /^master-library-.*\.json$/.test(f)).sort();
  if (!files.length) throw new Error('No RFI master library found under templates/rfi/');
  return path.join(dir, files[files.length - 1]);
}

function main() {
  const libFile = newestMasterLibrary();
  const lib = JSON.parse(fs.readFileSync(libFile, 'utf8'));
  delete lib._how_to_use;                       // authoring guidance, not content

  const firstPersona = Object.values(lib._personas || {})[0] || {};
  lib.name = (lib.access && lib.access.tool) || (firstPersona.access && firstPersona.access.tool) ||
    lib.referenceTool || 'RFIs';

  let html = fs.readFileSync(APP, 'utf8');
  const start = html.indexOf('  const RFI_SEED = ');
  if (start < 0) { console.error('RFI_SEED not found in the app.'); process.exit(1); }

  // find the end of the declaration: the first line that is exactly "  };"
  const endMarker = '\n  };';
  const end = html.indexOf(endMarker, start);
  if (end < 0) { console.error('Could not find the end of RFI_SEED.'); process.exit(1); }

  const json = JSON.stringify(lib, null, 2)
    .split('\n').map((l, i) => (i === 0 ? l : '  ' + l)).join('\n')
    .replace(/<\/script/gi, '<' + String.fromCharCode(92) + '/script');

  const before = html.slice(start, end + endMarker.length);
  const after = '  // Generated by scripts/sync-seed.js from ' +
    path.relative(ROOT, libFile).replace(/\\/g, '/') + ' — do not edit by hand.\n' +
    '  const RFI_SEED = ' + json + ';';

  html = html.slice(0, start) + after + html.slice(end + endMarker.length);
  fs.writeFileSync(APP, html);

  const count = (k) => (lib[k] || []).length;
  console.log('Seed synced from ' + path.relative(ROOT, libFile));
  console.log('  steps ' + count('steps') + ' · checklist ' + count('checklist') + ' · issues ' + count('issues'));
  ['procedureIntro', 'closeoutIntro', '_personas'].forEach((k) => {
    console.log('  ' + k.padEnd(16) + (lib[k] ? 'carried' : 'MISSING FROM THE LIBRARY'));
  });
  console.log('  size ' + (before.length / 1024).toFixed(1) + ' KB -> ' + (after.length / 1024).toFixed(1) + ' KB');
}

main();
